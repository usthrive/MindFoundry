/**
 * sm-dump-days — G1-U02's DAYS as plain readable text, for the owner and the authenticity
 * judges (BUILD-PLAN stage 1 "Owner reads"; EXEMPLAR §10 item 4).
 *
 * Run (from frontend/): npx tsx scripts/sm-dump-days.ts > ../modules/school-math/testing/dump-g1u02-stage1-run2.txt
 *
 * At seeds 3 and 16, from a simulated child's real history (sm-lib-sim; a child who gets
 * most first tries right, so the day shows a weakest-skill return beside any comeback):
 *   - the L4 lesson day (the N + 1 day: starter, demo, three steps with the explain item, two exits);
 *   - the practice day after L5, with a return and the preview ("try a new one");
 *   - the W1 fix-it after two shown answers (one twin then answered right, one missed), and
 *     "look again" at the end of that day (the miss fixed at rung 2, the one whose twin was missed);
 *   - the chapter check G1-U02-CK.
 * Each slot shows its role, whether it counts in N, and why it holds its template.
 */
import { G1_U02 } from '../src/modules/school-math/curriculum/grade1'
import {
  CHECK_SCREEN_LINES, REVIEW_OPENING_LINE, attemptFrom, dayScore, fixItAfterShown, lookAgain,
} from '../src/modules/school-math/engine/assemble'
import { comebackLedger } from '../src/modules/school-math/engine/scheduler'
import type { SMDay, SMItem } from '../src/modules/school-math/types'
import { simulateUnit, instantOn } from './sm-lib-sim'
import { item, out, w } from './sm-lib-print'

function dayHeader(d: SMDay) {
  const m = d.manifest
  w(`  day ${m.dayKey} · ${m.dayKind} · ${m.lessonId} · N = ${m.n} · manifest hash ${d.hash}`)
  for (const s of m.slots) {
    w(`    slot ${s.index + 1}: ${s.role.padEnd(9)} ${s.inN ? 'in N ' : 'not N'}  ${s.templateId ?? '(the teacher\'s demo)'}${s.options ? ` ${JSON.stringify(s.options)}` : ''}  — ${s.source}${s.comebackKey ? ` [comeback ${s.comebackKey}]` : ''}`)
  }
  w()
}

function findDays(seed: number) {
  for (const rightRate of [0.95, 0.9, 0.98, 1]) {
    const sim = simulateUnit(G1_U02, seed, { rightRate })
    const p5 = sim.days.find((d) => d.kind === 'practice' && d.lessonId === 'G1-U02-L5')!
    const ok = p5.items.some((i) => i.role === 'return') && p5.items.some((i) => i.role === 'preview')
    if (ok) return { sim, rightRate }
  }
  return { sim: simulateUnit(G1_U02, seed, { rightRate: 0.95 }), rightRate: 0.95 }
}

const ARGS = process.argv.slice(2).map(Number).filter((n) => Number.isInteger(n) && n >= 0)
const SEEDS = ARGS.length ? ARGS : [3, 16]

w('G1-U02 — stage 1, run 2 dump: days (generated by frontend/scripts/sm-dump-days.ts)')
w(`Seeds ${SEEDS.join(' and ')}. A simulated child (no name) walks the unit: entry check, L1 lesson, practice, … L6, practice, check.`)
w('"in N" = counted in "Question k of N"; the demo, the fix-it twin and "look again" never are. No exam values.')
w()

for (const seed of SEEDS) {
  const { sim, rightRate } = findDays(seed)
  w(`################  SEED ${seed}  (simulated child: first try right with chance ${rightRate})  ################`)
  w()
  const l4 = sim.days.find((d) => d.kind === 'lesson' && d.lessonId === 'G1-U02-L4')!
  w(`=== LESSON DAY · L4 subtract (the N + 1 day) ===`)
  dayHeader(l4.day!)
  const demo = l4.day!.demo
  if (demo) w(`  the teacher's demo (not counted, never an attempt): ${demo.says} — facts ${demo.facts.map((f) => `${f.whole} = ${f.parts.join(' + ')}`).join(', ')}`)
  w()
  for (const it of l4.items) item(it, '  ')

  const p5 = sim.days.find((d) => d.kind === 'practice' && d.lessonId === 'G1-U02-L5')!
  const before = sim.attempts.filter((a) => a.localDay < p5.dayKey)
  const due = comebackLedger(before).filter((e) => !e.settled)
  w(`=== PRACTICE DAY · after L5 (current 5, returns 2, preview ≤ 1) ===`)
  w(`  open comebacks before this day: ${due.length ? due.map((e) => `${e.templateId.replace('sm.g1u02.', '')} (${e.source}, due ${e.dueOn})`).join('; ') : 'none'}`)
  dayHeader(p5.day!)
  for (const it of p5.items) item(it, '  ')

  // W1 then W2 from a fixture: three first-try misses — slot A fixed at rung 2; slot B shown at
  // rung 4 and its fix-it twin answered right; slot C shown at rung 4 and its twin missed
  const items = p5.items.filter((i) => i.role !== 'preview')
  const missA = items[1], missB = items[3], missC = items[5]
  const slot = (it: SMItem) => p5.items.indexOf(it) + 1
  const atts = p5.items.map((it, k) => attemptFrom(it, { dayKind: 'practice', localDay: p5.dayKey, createdAt: instantOn(p5.dayKey, k) }, {
    firstTryCorrect: ![missA, missB, missC].includes(it),
    answers: [missA, missB, missC].includes(it) ? ['(his first answer)'] : ['(right)'],
    ladderRung: it === missA ? 2 : it === missB || it === missC ? 4 : 0,
  }))
  for (const [m, right] of [[missB, true], [missC, false]] as const) {
    const fx = fixItAfterShown(m, p5.items)
    w(`=== W1 FIX-IT · straight after slot ${slot(m)} reached rung 4 (the answer shown); fixture: the twin is answered ${right ? 'right' : 'wrong'} first try ===`)
    if (fx.kind === 'none') { w(`  none: ${fx.reason}`); continue }
    w(`  ${fx.kind}: role review, not in N`)
    item(fx.item, '  ')
    atts.push(attemptFrom(fx.item, { dayKind: 'practice', localDay: p5.dayKey, createdAt: instantOn(p5.dayKey, 20 + slot(m)) }, { firstTryCorrect: right, ladderRung: right ? 0 : 2 }))
  }
  const la = lookAgain(p5.items, atts, 2, { dayKind: 'practice' })
  w(`=== LOOK AGAIN · end of that practice day (misses: slot ${slot(missA)} fixed at rung 2; slot ${slot(missB)} shown, twin right — skipped; slot ${slot(missC)} shown, twin missed) ===`)
  w(`  day score before review: ${dayScore(p5.items, atts).right} of ${dayScore(p5.items, atts).of} first try`)
  for (const x of la) {
    w(`  look again at ${x.fromItemId}: ${x.twin ? 'the answer was shown, so a fresh-number twin' : 'the same question, his own answer shown'} · starts at rung ${x.startRung} · says "${x.line}"${x.ownAnswer ? ` · shows his answer: ${x.ownAnswer}` : ''}`)
    item(x.item, '    ')
  }
  const after = dayScore([...p5.items, ...la.map((x) => x.item)], [...atts, ...la.map((x, k) => attemptFrom(x.item, { dayKind: 'practice', localDay: p5.dayKey, createdAt: instantOn(p5.dayKey, 30 + k) }, { firstTryCorrect: true, answers: ['review: (right)'] }))])
  w(`  day score after both look-again answers are right: ${after.right} of ${after.of} (unchanged: review answers never count)`)
  w()

  // the check as the simulated child met it: drawn with his last 7 days of served items
  const ck = sim.days.find((d) => d.kind === 'check')!.form!
  w(`=== CHAPTER CHECK G1-U02-CK (seed ${seed}; ${ck.totalPoints} points; feedback held; review after) ===`)
  w(`  check-screen lines: ${CHECK_SCREEN_LINES.map((l) => `"${l}"`).join(' · ')}; review opening line: "${REVIEW_OPENING_LINE}"`)
  w()
  for (const r of ck.rows) {
    w(`§ ${r.section} · ${r.points} pt · ${r.category} · ${r.note}`)
    item(r.item, '  ')
  }
}

console.log(out.join('\n'))
