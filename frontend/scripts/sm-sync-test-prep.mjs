// Copies the School Math stopgap pages (single sources of truth in
// modules/school-math/design/experience/) into public/school-math/ as complete documents, so the app
// serves them from its own origin:
//   TEST-PREP-SUBTRACTION.html → public/school-math/test-prep.html
//   BAR-MODELS-PRACTICE.html   → public/school-math/bar-models.html
// Run after every edit of a source page:
//   node scripts/sm-sync-test-prep.mjs            (writes both)
//   node scripts/sm-sync-test-prep.mjs --check    (fails if a copy is stale; battery)
//   node scripts/sm-sync-test-prep.mjs --selftest (broken control: a stale copy must fail the check)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const PAGES = [
  { src: 'TEST-PREP-SUBTRACTION.html', out: 'test-prep.html' },
  { src: 'BAR-MODELS-PRACTICE.html', out: 'bar-models.html' },
];

function generated(srcName) {
  const body = readFileSync(join(here, '../../modules/school-math/design/experience', srcName), 'utf8');
  return (
    '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">\n' +
    '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n' +
    '<meta name="robots" content="noindex">\n' +
    '<style>:root{color-scheme:light;box-sizing:border-box;padding-top:env(safe-area-inset-top,0px);' +
    'padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;padding:0;font:14px -apple-system,' +
    'BlinkMacSystemFont,sans-serif}img{max-width:100%}[hidden]:not([hidden=until-found i])' +
    '{display:none!important}</style>\n</head><body>\n' +
    '<!-- GENERATED by frontend/scripts/sm-sync-test-prep.mjs from ' +
    'modules/school-math/design/experience/' + srcName + '. Edit the source, then re-run. -->\n' +
    body + '\n</body></html>\n'
  );
}
const outPath = (p) => join(here, '../public/school-math', p.out);
const stale = (p, cur) => cur !== generated(p.src);

if (process.argv.includes('--selftest')) {
  // broken control: a served copy with one character changed must be reported stale, and the real copy must not
  let ok = true;
  for (const p of PAGES) {
    const cur = existsSync(outPath(p)) ? readFileSync(outPath(p), 'utf8') : '';
    const broken = cur.replace('</title>', ' </title>');
    const fired = stale(p, broken);
    console.log((fired ? 'fired' : 'MISSING') + ': a stale ' + p.out + ' fails the check');
    if (!fired) ok = false;
  }
  console.log(ok ? 'PASS: sync --check control fires for both pages' : 'FAIL: sync --check control');
  process.exit(ok ? 0 : 1);
} else if (process.argv.includes('--check')) {
  let bad = 0;
  for (const p of PAGES) {
    const cur = existsSync(outPath(p)) ? readFileSync(outPath(p), 'utf8') : '';
    if (stale(p, cur)) { console.error('FAIL: public/school-math/' + p.out + ' is stale; run node scripts/sm-sync-test-prep.mjs'); bad += 1; }
    else console.log('PASS: public/school-math/' + p.out + ' matches its source');
  }
  process.exit(bad ? 1 : 0);
} else {
  for (const p of PAGES) {
    const doc = generated(p.src);
    writeFileSync(outPath(p), doc);
    console.log('wrote', outPath(p), doc.length, 'bytes');
  }
}
