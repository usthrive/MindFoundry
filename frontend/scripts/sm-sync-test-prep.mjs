// Copies the School Math test-prep page (single source of truth:
// modules/school-math/design/experience/TEST-PREP-SUBTRACTION.html) into
// public/school-math/test-prep.html as a complete document, so the app serves it
// from its own origin. Run after every edit of the source page:
//   node scripts/sm-sync-test-prep.mjs        (writes)
//   node scripts/sm-sync-test-prep.mjs --check (fails if the copy is stale; battery)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../../modules/school-math/design/experience/TEST-PREP-SUBTRACTION.html');
const out = join(here, '../public/school-math/test-prep.html');
const body = readFileSync(src, 'utf8');
const doc =
  '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n' +
  '<meta name="robots" content="noindex">\n' +
  '<style>:root{color-scheme:light;box-sizing:border-box;padding-top:env(safe-area-inset-top,0px);' +
  'padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;padding:0;font:14px -apple-system,' +
  'BlinkMacSystemFont,sans-serif}img{max-width:100%}[hidden]:not([hidden=until-found i])' +
  '{display:none!important}</style>\n</head><body>\n' +
  '<!-- GENERATED by frontend/scripts/sm-sync-test-prep.mjs from ' +
  'modules/school-math/design/experience/TEST-PREP-SUBTRACTION.html. Edit the source, then re-run. -->\n' +
  body + '\n</body></html>\n';
if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== doc) { console.error('FAIL: public/school-math/test-prep.html is stale; run node scripts/sm-sync-test-prep.mjs'); process.exit(1); }
  console.log('PASS: public/school-math/test-prep.html matches its source');
} else {
  writeFileSync(out, doc);
  console.log('wrote', out, doc.length, 'bytes');
}
