/**
 * THE RECIPE'S HEADLINE (§6 row E1, "scale then compare recipes"). Two mixes
 * are written for different numbers of lemons, so they cannot be compared as
 * they stand: the first has to be grown to the second's lemon count before the
 * two amounts of water mean anything beside each other. The chain is therefore
 * scale, then compare — and the answer is the gap the scaling reveals.
 *
 * The draw fixes the second recipe to be the LEMONIER of the two (its water is
 * short of the scaled-up first recipe by a positive amount), which is what
 * makes the Day-5 defence a real defence: the jug with more lemons in it is not
 * the strong one.
 */
const msScaleThenCompare = multiStep({
  situationType: 'comparison',
  cognitiveOp: 'ratio-compare',
  draw: (r) => {
    // Water outruns lemons in both recipes, so neither jug is a syrup: the
    // second recipe's stated water is bounded below by its own lemon count.
    const lemons = r.int(2, 5);
    const cups = lemons + r.int(1, 5);
    const k = r.int(3, 6);
    // short ≥ 2, so the two recipes never coincide and the answer is never a
    // count of one (which would print "1 cups" through countNoun). The upper
    // bound keeps the second recipe's water strictly above its lemon count,
    // so neither jug in the story is a syrup. (cups − lemons) · k ≥ 3, so the
    // range never inverts.
    const short = r.int(2, Math.min(6, (cups - lemons) * k - 1));
    const rival = cups * k - short;
    return {
      prompt: `One lemonade recipe uses ${countNoun(cups, 'cups')} of water for every ${countNoun(lemons, 'lemons')}. A second recipe uses ${countNoun(rival, 'cups')} of water with ${countNoun(lemons * k, 'lemons')}. Scaled up to ${countNoun(lemons * k, 'lemons')} with its ratio unchanged, how many more cups of water does the first recipe need than the second?`,
      initN: cups,
      steps: [
        { op: 'mul', n: k, d: 1 },
        { op: 'sub', n: rival, d: 1 },
      ],
      units: 'cups',
      hints: [
        'Can two recipes be judged against each other while one of them is written for fewer lemons than the other?',
        'Grow the first recipe until its lemons match the second recipe\'s, then set the two amounts of water side by side.',
      ],
      errorTags: ['concept-misconception', 'task-comprehension'],
    };
  },
});

/**
 * INVERSE-START (PEDAGOGY-CEILING-REVIEW F3, the Level-E lift). The quantity the
 * story hands over is the RESULT of the scaling, not one of the recipe's own
 * numbers, so the opening move is a division nothing in the sentence order asks
 * for: find how many times the recipe was taken, and only then build the batch.
 *
 * Served through the check-back wrapper, because the honest check on an undone
 * scaling is not "is the arithmetic right" but "does the pair I ended with
 * still stand in the recipe's ratio" — which is the week's rule used backwards.
 */
const msUnscaleThenTotal = multiStep({
  situationType: 'part-whole',
  cognitiveOp: 'ratio-unscale',
  posing: 'inverse-start',
  usesPriorSkill: true,
  draw: (r) => {
    const grit = r.int(2, 5);
    // loam > grit, so the recipe is never 1 : 1 (where scaling and adding
    // would be indistinguishable in the answer, not just in the child's head).
    const loam = grit + r.int(1, 4);
    const k = r.int(3, 7);
    return {
      prompt: `A batch of potting compost used ${countNoun(loam * k, 'litres')} of loam. It was mixed to a recipe of ${countNoun(grit, 'litres')} of grit for every ${countNoun(loam, 'litres')} of loam. How many litres of grit and loam went into the batch altogether?`,
      initN: loam * k,
      steps: [
        { op: 'div', n: loam, d: 1 },
        { op: 'mul', n: grit, d: 1 },
        { op: 'add', n: loam * k, d: 1 },
      ],
      units: 'litres',
      hints: [
        'Does the amount of loam in this story come from the recipe line, or from the recipe already scaled up?',
        'Work out how many times the recipe was taken, then build both parts of the batch from that.',
      ],
      errorTags: ['concept-misconception', 'procedure-slip'],
    };
  },
});
const msUnscaleThenTotalCheck = withCheckBack(
  msUnscaleThenTotal,
  'do the two amounts you have found stand in the same ratio the recipe names?',
);

/**
 * HAS-DISTRACTOR (PEDAGOGY-CEILING-REVIEW F3). Two things separate this from the
 * combine-then-scale chain: the order is reversed (scale first, then add), and
 * the amount added afterwards is NOT part of the ratio, so it must not be
 * scaled with it. The number of loaves is stated and never used — and it is the
 * seductive kind of spare quantity, because dividing by it is a move the story
 * almost invites.
 */
const msScaleThenAdd = multiStep({
  situationType: 'multi-stage',
  cognitiveOp: 'ratio-scale-then-add',
  posing: 'has-distractor',
  draw: (r) => {
    // Water is drawn AS A SHARE of the flour — 40% to 70%, the hydration range
    // a real dough lives in — so the ratio the item scales is one a baker would
    // recognise. Flour is a multiple of 50, so the share is always whole.
    const flour = r.int(2, 3) * 50;
    const water = (flour * r.int(4, 7)) / 10;
    const k = r.int(3, 6);
    const extra = r.int(2, 9) * 5;
    const loaves = r.int(3, 8);
    const name = one(r);
    return {
      prompt: `A bread dough uses ${countNoun(water, 'grams')} of water for every ${countNoun(flour, 'grams')} of flour. ${name} mixes a dough with ${countNoun(flour * k, 'grams')} of flour, then works in another ${countNoun(extra, 'grams')} of water to soften it. The dough is shaped into ${countNoun(loaves, 'loaves')}. How much water goes into the dough in all?`,
      initN: water,
      steps: [
        { op: 'mul', n: k, d: 1 },
        { op: 'add', n: extra, d: 1 },
      ],
      units: 'grams',
      hints: [
        'Which amount in this story grows with the flour, and which one is simply tipped in afterwards?',
        'Scale the water that belongs to the flour first, then bring in what was added later — and leave alone the number that counts something else.',
      ],
      errorTags: ['task-comprehension', 'representation-misread'],
    };
  },
});

