/**
 * Level E · Week 1 — "Ratios" (conceptId: ratios).
 *
 * The Level-E v2 EXEMPLAR. FILL-ARCHITECTURE §6 row E1: anchor "the ratio table
 * as a structure-preserving machine"; key multi-step "scale then compare
 * recipes"; error-analysis "adds the same number to both terms"; discrimination
 * "additive vs multiplicative growth"; Day-5 signature "which is more lemony —
 * a defence".
 *
 * The week's whole claim is that a ratio names a RELATIONSHIP and not a pair of
 * sizes, so the only edit it survives is one that multiplies both terms by the
 * same factor. Everything below is built to force that distinction rather than
 * announce it:
 *  - two discriminations that attack the additive misconception from opposite
 *    sides. `additiveVsMultiplicativeGrowth` asks the child to PRODUCE the term
 *    that keeps a mix the same; the row-integrity item asks them to DETECT the
 *    one pair among three that cannot have come from a table — and the impostor
 *    row is generated by the family's own `additiveScalingTerm`, so it is the
 *    genuine output of the misconception. The two rationales on that item are
 *    the same error seen from the other end: an additive reader keeps the row
 *    whose GAP is unchanged and rejects the true rows, because scaling is the
 *    one move that leaves the gap alone;
 *  - a generated error-analysis (`eaScaleByAdding`) whose shown wrong number is
 *    a real misconception output, re-derived by QG-11;
 *  - six genuine multi-step items across four shapes: combine-then-scale,
 *    scale-then-compare (the recipe's headline, and the arithmetic the Day-5
 *    defence rests on), scale-then-add-an-unscaled-extra, and an inverse-start
 *    chain that has to undo a scaling before it can total anything;
 *  - the three Level-E ceiling lifts, each carried by a different item:
 *    INVERSE-START (the compost batch: the stated quantity is the RESULT of the
 *    scaling), HAS-DISTRACTOR (the dough: the loaf count is stated and never
 *    used — dividing by it is the seductive extra step), and CHECK-BACK (the
 *    same compost item, wrapped: the honest check on an unscaled answer is
 *    whether the pair you wrote still stands in the recipe's ratio).
 *
 * FIGURE LAW as applied here (FANOUT kit §F.7 / §E2.5): every figure on a DAY
 * ITEM shows what the child was HANDED — the opening row of a table with the
 * asked cell left as '?', the two bars of the ratio before any scaling — and is
 * built from the item's own drawn params. The pictures that show a completed
 * journey live where the answer is already on the page: the lesson script and
 * the guided examples.
 *
 * TWO AUTHORING DECISIONS, recorded here rather than buried (§E2.3 convention):
 *
 *  1. `partWholeVsPartPart` is NOT served, although it is one of the family's
 *     E1 generators. It draws from the same COLLECTIONS pool as
 *     `partToWholeShare` and opens with the same sentence ("A box holds P gold
 *     beads for every Q glass beads…"), so a week carrying both prints one
 *     sentence twice with new numbers. `partToWholeShare` is kept — it computes
 *     the share rather than choosing it — and the part:part↔part:whole reading
 *     is carried instead by the Day-5 vocabulary and the parent note.
 *
 *  2. The ratio table is drawn with `areaGrid` (two columns, cell labels) and
 *     ships WITHOUT an `asserts` clause. The figure library has no table
 *     primitive, and area-grid's assertable quantities — `shaded` and `cells` —
 *     name nothing a table cell means, so an assertion here would audit the
 *     wrong number. The picture is still built from the item's own params by
 *     construction (`withFigure` reads `generator.params`), and it shows only
 *     given cells plus a '?' where the question is.
 *
 * Retrieval is backward-only into the four Level-D skills a ratio actually runs
 * on: D9 equivalence by scaling (the direct ancestor — top and bottom grow by
 * the same factor), D4 "times as many", D16 exact division (the move that
 * recovers a scale factor) and D15 multiplication fluency.
 */

