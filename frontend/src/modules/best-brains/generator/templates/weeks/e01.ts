// Discrimination — the additive misconception, from both ends
// ---------------------------------------------------------------------------

/**
 * Row integrity: three pairs are offered as later rows of one table, and the
 * impostor is the row the ADDITIVE scaler writes — `additiveScalingTerm`, the
 * family's own code for the misconception, supplies its second term.
 *
 * The two distractor rationales are the same error read from the other side.
 * Adding a fixed amount to both terms is the one move that PRESERVES the gap
 * between them, so the impostor row is the only one whose two numbers are still
 * the original distance apart — which is exactly why a child reasoning by gaps
 * keeps it and throws out the genuine rows instead.
 */
const discrimRowIntegrity = discrimination({
  variant: 'structural',
  cognitiveOp: 'ratio-table-integrity',
  draw: (r) => {
    const a = r.int(2, 6);
    // b > a, so "same gap" and "same ratio" cannot agree, and k ≥ 4 keeps the
    // impostor's first term clear of the two genuine rows on offer.
    const b = a + r.int(1, 5);
    const k = r.pick([4, 5]);
    return {
      prompt: `One ratio table begins with the row ${a} : ${b}. Three more pairs are offered as later rows of it. Which pair could NOT belong?`,
      correct: `${a * k} : ${additiveScalingTerm(a, b, k)}`,
      distractors: [
        {
          text: `${2 * a} : ${2 * b}`,
          errorTag: 'concept-misconception',
          rationale: 'A genuine row — both terms doubled. It is thrown out by a reader who tests whether the two numbers changed by the same AMOUNT, which no scaled row ever does.',
        },
        {
          text: `${3 * a} : ${3 * b}`,
          errorTag: 'representation-misread',
          rationale: 'Also a genuine row — both terms tripled. It is thrown out by a reader who expects the gap between the two numbers to stay put, and this is the row whose gap has grown the most.',
        },
      ],
      hints: [
        'How could you test a single pair, on its own, to see whether it belongs to a table?',
        'Reduce each pair to its simplest form and set the three results beside the opening row.',
      ],
      errorTags: ['concept-misconception', 'representation-misread'],
    };
  },
});

